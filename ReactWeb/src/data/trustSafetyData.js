export function getTrustClassification(score) {
  if (score >= 80) return TRUST_CLASSIFICATIONS.TRUSTED;
  if (score >= 60) return TRUST_CLASSIFICATIONS.OBSERVATION;
  if (score >= 40) return TRUST_CLASSIFICATIONS.WARNING;
  return TRUST_CLASSIFICATIONS.HIGH_RISK;
}

export function getVerificationStatusStyle(status) {
  const styles = {
    'Verified': { color: '#0e8048', bg: '#e8f6ed' },
    'Pending': { color: '#d97706', bg: '#fef3c7' },
    'Under Review': { color: '#0057b8', bg: '#e8f2fa' },
    'Rejected': { color: '#dc2626', bg: '#fef2f2' },
    'Suspended': { color: '#ea580c', bg: '#fff7ed' },
    'Banned': { color: '#7c3aed', bg: '#f5f3ff' },
  };
  return styles[status] || { color: '#64748b', bg: '#f1f5f9' };
}

